// Hand-weapon configuration with authored and resolved projectile references.
// Heat accumulates per shot and cools over time; secondary fire may share the primary heat pool.
// [INFERRED] Source placement.

#ifndef GAME_OBJECTS_GENERICFIREARMTEMPLATE_H     // [INFERRED] guard style
#define GAME_OBJECTS_GENERICFIREARMTEMPLATE_H

#include <string>

#include "AnimatedBundleTemplate.h"
#include "IItemTemplate.h"

namespace dice {
namespace hfe {

class GameLogic;      // selectWeapon reads the two device flags below - see the friend
namespace hud { class HudMessages; }

namespace world {

class FireComp;

class GenericFireArmTemplate : public AnimatedBundleTemplate, public IItemTemplate
{
    // Weapon selection reads gas-mask and night-vision flags directly.
    friend class ::dice::hfe::GameLogic;
    friend class ::dice::hfe::hud::HudMessages; // PE79E1DA: excludes gas-mask/night-vision items
    // Soldier reads selection, equipment, and deployment settings directly.
    friend class Soldier;
    // The runtime firearm reads its template configuration directly.
    friend class GenericFireArm;
    // FireComp::destroy reads m_keepProjectiles directly in both shipped ports; no accessor exists.
    friend class FireComp;

public:
    // Initializes weapon settings while preserving the uninitialized fields documented in the body.
    GenericFireArmTemplate();

    // Own reference count and interface lookup, including IItemTemplate.
    virtual void addRef();
    virtual int getRef();
    virtual int release();
    virtual void* queryInterface(unsigned int iid) const;

    // Identifies the firearm template independently of its base.
    virtual unsigned int getClassID() const;              // +0x10 38099
    // answers TWO CIDs (its own AND AnimatedBundleTemplate's) then chains past its parent
    // straight to BundleTemplate::queryImplementation. Shipped shape; see the .cpp.
    virtual void* queryImplementation(unsigned int cid);  // +0x50

    // retail's body is `new GenericFireArm(this)`; the product
    // constructor carries the attested pre-cache cascade at its shipped site.
    virtual IObject* createObject() const;                // +0x54 retail 47 B

    // the weapon half of the projectile pre-store cascade.
    virtual void preCache() const;                        // +0x6C

    // IItemTemplate @ +404. These four accessors are the exact tail of its eight-slot secondary
    // table (ELF 0x8256CC0..0x8256D40); the console uses this face for itemIndex/itemType.
    virtual void setItemIndex(int itemIndex);
    virtual int getItemIndex() const;
    virtual void setItemType(int itemType);
    virtual int getItemType() const;

    // the lazy authored-name -> resolved-pointer hop.
    IObjectTemplate* getProjectileTemplate();
    // identical lazy hop for the alternate projectile.
    IObjectTemplate* getSecondaryProjectileTemplate();


    // The delay's tick cache is the reason this one is a method: it writes both fields, and the
    // tick count is a truncating conversion (`cvttss2si`), not a rounding one.
    void setDelayToUse(float seconds);

    // clamped AT 10.0f, and the clamp is written `v = 10.0f; if (arg < 10.0f) v = arg;` - so a
    // NaN argument stores 10.0f rather than propagating. Reproduced in that shape deliberately.
    void setOverheatPenalty(float penalty);

protected:
    // layout, offsets 404..519. AnimatedBundleTemplate occupies 0..403.
    // The IItemTemplate vptr at +404 is compiler-generated by the real secondary base above.
    /* 408 */ int   m_refCount4;

    // These public fields are written directly by ObjectTemplate console bindings; preserve declaration order.
public:
    /* 412 */ float m_delayToUse;                    // read by the GET arm; written via setDelayToUse
protected:
    /* 416 */ int   m_delayToUseTimes30;             // cached tick count - setDelayToUse's second store
    /* 420 */ int   _dword1A4;                       // [UNRESOLVED]

public:
    // The console accepts hideFirstPerson, but makeScript emits setHideFirstPerson;
    // this mismatch prevents that property from round-tripping.
    /* 424 */ bool  m_setHideFirstPerson;
protected:
    /* 425 */ bool  _byte1A9;                        // [UNRESOLVED] 425..431
    /* 426 */ bool  _byte1AA;
    /* 427 */ bool  _byte1AB;
    /* 428 */ bool  _byte1AC;
    /* 429 */ bool  _byte1AD;
    /* 430 */ bool  _byte1AE;
    /* 431 */ bool  _byte1AF;

    // overheat model
public:
    /* 432 */ float m_heatAddWhenFire;
    /* 436 */ float m_coolDownPerSec;
    /* 440 */ float m_overheatPenalty;               // written via setOverheatPenalty (clamped)
    /* 444 */ bool  m_inheritHeatFromPrimary;        // alt-fire shares the primary's heat pool
protected:

    /* 448 */ int   m_itemIndex;
    /* 452 */ int   m_itemType;

public:
    /* 456 */ float m_velocity;
    /* 460 */ int   m_weaponType;
protected:
    /* 464 */ int   m_weaponClass;
    /* 468 */ bool  m_worksInWater;

    // Console assignment writes the projectile name and clears its resolved cache directly.
public:
    /* 472 */ std::string m_projectileTemplateName;
    /* 476 */ std::string m_secondaryProjectileTemplateName;
    /* 480 */ IObjectTemplate* m_projectileTemplate;
    /* 484 */ IObjectTemplate* m_secondaryProjectileTemplate;

    // `ObjectTemplate.secondaryProjectileTemplate` (ConsoleClass324, 0x85C3E80) is the exact mirror
    // of the primary: assign the name at +476, null the resolved cache at +484.
public:
    /* 488 */ float m_keepProjectiles;

    // Names below from the console property -> field offset join.
    /* 492 */ bool  m_isSelectable;
    // NOT a conflict - the same two-vocabulary effect proven on KitTemplate+424: the C++ member name
    // and the .con property name for one field simply differ. `forceSustainedFire` is what a .con
    // file writes; `m_canInternalHandleMessage` is the member name. Neither is wrong.
    // [UNRESOLVED] the member name is not independently attested here (no accessor exists for
    // either spelling), unlike the KitTemplate case where Kit::getCreationIndex settled it.
    /* 493 */ bool  m_canInternalHandleMessage;      // .con property name: `forceSustainedFire`
// Console properties access these equipment fields directly.
public:
    /* 494 */ bool  m_isGasMask;                     // was `_byte1EE`
    /* 495 */ bool  m_isNightVision;                 // was `_byte1EF`

    /* 496 */ float m_deployAnimationTime;           // was `_dword1F0`; ctor 1.0f
public:
    /* 500 */ std::string m_blockInputOnRotBundle;
// Console bindings access the GUI and fire-mode settings directly.
public:
    /* 504 */ int   m_canFireGuiIndex;               // was `_dword1F8`; closes the whole 504..519
    /* 508 */ int   m_cannotFireGuiIndex;            // was `_dword1FC`
    // ... 1.0f here and 3.0f (0x40400000) below - all three are floats by ctor evidence.
    /* 512 */ float m_cannotFireTimer;               // was `_dword200`; ctor 1.0f
    /* 516 */ float m_crosshairFireTime;             // was `_dword204`; ctor 3.0f

    // [CHOSEN, not recovered] Project Reality's ObjectTemplate.proneOnlyReload, appended past the
    // retail layout: the weapon reloads only while prone, and its soldier cannot leave prone during
    // the reload. Enforced on player input; see GameServer::simulatePlayerUpdate.
    /* 520 */ bool  m_proneOnlyReload;
};

} // namespace world
} // namespace hfe
} // namespace dice

#endif // GAME_OBJECTS_GENERICFIREARMTEMPLATE_H
